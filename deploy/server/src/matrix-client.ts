import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { betterAuth } from "better-auth";
import * as z from "zod";

type Adapter = Pick<
	Awaited<ReturnType<typeof betterAuth>["$context"]>["adapter"],
	"findOne" | "create" | "update"
>;
const credentialsSchema = z
	.object({
		clientId: z.literal("matrix-synapse-local"),
		clientSecret: z.string().min(32),
	})
	.strict();
export const matrixClientId = "matrix-synapse-local";
export const matrixCallback =
	"http://localhost:8008/_synapse/client/oidc/callback";

/** Read private local credentials generated by the Matrix setup command. */
export function readMatrixCredentials() {
	const path = fileURLToPath(
		new URL("../../matrix/.runtime/oidc.json", import.meta.url),
	);
	return existsSync(path)
		? credentialsSchema.parse(JSON.parse(readFileSync(path, "utf8")))
		: undefined;
}

/** Provision only the deployment-owned Synapse client; no browser can invoke this. */
export async function ensureMatrixClient(
	adapter: Adapter,
	credentials: z.infer<typeof credentialsSchema>,
) {
	const data = {
		clientId: credentials.clientId,
		clientSecret: createHash("sha256")
			.update(credentials.clientSecret)
			.digest("base64url"),
		name: "Matrix · Synapse",
		redirectUris: [matrixCallback],
		tokenEndpointAuthMethod: "client_secret_basic",
		applicationType: "native",
		grantTypes: ["authorization_code"],
		responseTypes: ["code"],
		scopes: ["openid", "profile"],
		requirePKCE: true,
		skipConsent: false,
		subjectType: "public",
		disabled: false,
		updatedAt: new Date(),
	};
	const where = [{ field: "clientId", value: credentials.clientId }];
	const existing = await adapter.findOne({ model: "oauthClient", where });
	if (existing)
		await adapter.update({ model: "oauthClient", where, update: data });
	else
		await adapter.create({
			model: "oauthClient",
			data: { ...data, createdAt: new Date() },
		});
}
